                              } else if (failVal == 1) {
                                cellColor <- "fail"
                              }
                            }
                          }

                          cat("\\\\cellcolor{", cellColor, "} ", cellText, sep = "")

                          if (j < length(chunk)) {
                            cat(" & ")
                          } else {
                            cat(" \\\\\\\\\\n\\\\hline\\n")
                          }
                        }
