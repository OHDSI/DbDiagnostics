              currentSettings <- s
              break
            }
          }

          if (is.null(currentSettings)) {
            for (s in analysisSettings) {
              if (!is.null(s$analysisName) && s$analysisName == analysisName) {
                currentSettings <- s
                break
              }
            }
          }

          if (!is.null(currentSettings)) {
            cat("\\\\pagebreak\\n")
            cat("\\\\begin{center}\\n")
            cat("\\\\large\\\\textbf{Analysis Specifications}\\n")
            cat("\\\\end{center}\\n\\n")

            cat("\\\\begin{infobox}\\n")
            cat("\\\\faInfoCircle\\\\hspace{0.3cm}The following parameters were used to configure this analysis.\\n")
            cat("\\\\end{infobox}\\n\\n")

            specGroups <- list(
              list(
                title = "Population Criteria",
                fields = list(
                  list(name = "minAge", label = "Minimum Age"),
                  list(name = "maxAge", label = "Maximum Age"),
                  list(name = "studyStartDate", label = "Study Start Date"),
                  list(name = "studyEndDate", label = "Study End Date"),
                  list(name = "requiredDurationDays", label = "Required Duration (Days)")
                )
              ),
              list(
                title = "Domain Requirements",
                fields = list(
                  list(name = "requiredDomains", label = "Required Domains"),
                  list(name = "desiredDomains", label = "Desired Domains"),
                  list(name = "requiredVisits", label = "Required Visits"),
                  list(name = "desiredVisits", label = "Desired Visits")
                )
              ),
              list(
                title = "Cohort Definitions",
                fields = list(
                  list(name = "targetName", label = "Target"),
                  list(name = "comparatorName", label = "Comparator"),
                  list(name = "indicationName", label = "Indication"),
                  list(name = "outcomeName", label = "Outcome")
                )
              ),
              list(
                title = "Additional Settings",
                fields = list(
                  list(name = "targetUseDrugEra", label = "Target Use Drug Era"),
                  list(name = "comparatorUseDrugEra", label = "Comparator Use Drug Era")
                )
              )
            )

            for (group in specGroups) {
              hasData <- FALSE
              for (field in group$fields) {
                val <- currentSettings[[field$name]]
                if (!is.null(val) && length(val) > 0 && !all(is.na(val))) {
                  hasData <- TRUE
                  break
                }
